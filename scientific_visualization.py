"""## Phase 6 — Unsupervised Cluster Optimization: Elbow & Silhouette Analysis

Before running partitioning algorithms, determining the optimal number of clusters ($K$) is essential. To avoid subjective choices, we employ a data-driven evaluation framework testing a range of cluster sizes ($K \in [2, 8]$).

Our pipeline implements:
1. **Iterative K-Means Modeling:** Fitting multiple K-Means models over a defined range of $K$ values using robust initializations (`n_init=20`) on the standardized continuous feature space.
2. **Elbow Method (Inertia):** Tracking the within-cluster sum of squares (inertia) to identify the point where the marginal gain of adding more clusters diminishes.
3. **Silhouette Analysis:** Computing the average silhouette score for each $K$ to measure how tightly grouped the data points are within clusters compared to neighboring partitions.
4. **Automated Optimal Selection:** Programmatically identifying the $K$ value that yields the maximum average silhouette score, highlighting the best choice on a dual-panel evaluation plot alongside a comprehensive summary metric table.

### Interpretation

The selected value of K represents the best solution among the tested configurations according to the Silhouette Score. However, the magnitude of the score must also be considered: a relatively low Silhouette value indicates that the intrinsic cluster structure is only weakly to moderately separated.

Therefore, K=2 should be interpreted as the most supported partition among the tested alternatives, not as evidence of two sharply separated natural populations.
"""

# Define the range of cluster numbers to evaluate and initialize metric storage lists
k_values = list(range(2, 9))
inertias = []
silhouettes = []

# Iterate through each candidate value of K to fit KMeans and compute evaluation metrics
