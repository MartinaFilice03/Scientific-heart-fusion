"""## Phase 10 — True supervised late fusion

Unlike early fusion techniques that indiscriminately concatenate raw data, a rigorously defined late-fusion architecture integrates information at the decision level by combining independent model probabilities rather than raw features or latent coordinates.

Our evaluation pipeline implements a strict multi-model framework:
Stratified Isolation: The patient cohort is partitioned once into training and independent test sets, preserving the exact target class distribution.
View-Specific Modeling: Two independent Random Forest classifiers are trained: one exclusively on the Clinical/Demographic view and another on the Diagnostic/Stress-Test view.
Probabilistic Integration (Late Fusion): The individual predicted probabilities from the two separate views are geometrically averaged to generate a unified, final diagnostic prediction.
Comparative Benchmarking: The late-fusion ensemble is systematically evaluated against the Clinical-only model, the Diagnostic-only model, and a standard flat 5-feature baseline.
Methodological Rigor: By subjecting all individual and fused models to the exact same hold-out patient subset, we guarantee absolute comparative consistency and prevent any potential data leakage across the evaluation metrics.
"""

# Perform stratified train-test data splitting based on target labels
indices = np.arange(len(df))
train_idx, test_idx = train_test_split(
    indices, test_size=0.20, stratify=y, random_state=RANDOM_STATE
)
y_train = y.iloc[train_idx]
y_test = y.iloc[test_idx]

# Define a helper function to train random forest and extract probabilities
def fit_rf_view(features):
    model = RandomForestClassifier(
        n_estimators=500,
        random_state=RANDOM_STATE,
        class_weight='balanced',
        n_jobs=-1
    )
    model.fit(df.iloc[train_idx][features], y_train)
    prob = model.predict_proba(df.iloc[test_idx][features])[:, 1]
    return model, prob

# Train view-specific and flat models to obtain out-of-fold probabilities
rf_clinical, prob_clinical = fit_rf_view(clinical_features)
rf_diagnostic, prob_diagnostic = fit_rf_view(diagnostic_features)
rf_flat, prob_flat = fit_rf_view(continuous_columns)

# Equal-weight late fusion of model outputs
prob_fusion = 0.5 * prob_clinical + 0.5 * prob_diagnostic
pred_fusion = (prob_fusion >= 0.5).astype(int)

# Evaluate and store performance metrics (accuracy and roc-auc) for all models
results = []
for name, prob in [
    ('Clinical view', prob_clinical),
    ('Diagnostic view', prob_diagnostic),
    ('Late fusion', prob_fusion),
    ('Flat 5-feature RF', prob_flat),
]:
    pred = (prob >= 0.5).astype(int)
    results.append({
        'Model': name,
        'Accuracy': accuracy_score(y_test, pred),
        'ROC_AUC': roc_auc_score(y_test, prob)
    })

# Compile performance dataframe, sort by roc-auc, and display results
performance_df = pd.DataFrame(results).sort_values('ROC_AUC', ascending=False)
display(performance_df.round(3))
