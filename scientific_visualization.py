"""## Phase 5.3 — PCA: Group Projections & 95% Confidence Ellipses

To evaluate the statistical spread and distribution overlap of each class within the principal component space, we augment our 2D scatter projection with formal covariance ellipses.

Our pipeline implements:
1. **Bivariate Covariance Estimation:** Calculating group-specific means and covariance matrices directly from the `PC1` and `PC2` coordinates for each target class.
2. **Eigen-Decomposition:** Determining eigenvalues and eigenvectors of the covariance matrices to define the orientation and principal axes of data dispersion.
3. **Chi-Square Scale Adjustment:** Utilizing the inverse cumulative distribution function of the chi-squared distribution (`chi2.ppf`) with two degrees of freedom ($\text{df}=2$) to scale the ellipse accurately for a 95% confidence level.
4. **Geometric Ellipse Patch Generation:** Constructing and overlaying custom `matplotlib.patches.Ellipse` boundary vectors with semi-transparent face colors and dashed borders onto the axes to visually delineate cluster dispersion.

### Interpretation

The covariance ellipses are used as descriptive summaries of the spatial distribution of the two target classes. Although the groups show a shift in their position within the PCA plane, substantial overlap remains between their distributions.

Therefore, the first two principal components reveal only partial class separation and should not be interpreted as providing a clear diagnostic boundary.g
"""

from matplotlib.patches import Ellipse

# Define helper function to calculate and draw bivariate confidence ellipses
def add_covariance_ellipse(x, y, ax, color, confidence=0.95):
    xy = np.column_stack([x, y])
    cov = np.cov(xy, rowvar=False)
    mean = xy.mean(axis=0)

    # Perform eigen-decomposition of the covariance matrix
    eigvals, eigvecs = np.linalg.eigh(cov)
    order = eigvals.argsort()[::-1]
    eigvals = eigvals[order]
    eigvecs = eigvecs[:, order]

    # Scale ellipse dimensions using chi-squared quantiles for df=2
    scale = np.sqrt(chi2.ppf(confidence, df=2))
    width, height = 2 * scale * np.sqrt(eigvals)
    angle = np.degrees(np.arctan2(eigvecs[1, 0], eigvecs[0, 0]))

    # Initialize figure and target color palette mapping
    ellipse = Ellipse(
        xy=mean, width=width, height=height, angle=angle,
        facecolor=color, edgecolor=color, alpha=0.12,
        linewidth=1.8, linestyle='--'
    )
    ax.add_patch(ellipse)

fig, ax = plt.subplots(figsize=(9, 6))
palette_target = {'Class 0': '#2b83ba', 'Class 1': '#d95f02'}

# Plot patient scatter points on pc1 and pc2 space
sns.scatterplot(
    data=pca_df, x='PC1', y='PC2', hue='Target',
    palette=palette_target, alpha=0.58, s=52, edgecolor='none', ax=ax
)

# Iterate over target classes to overlay group-wise 95% confidence ellipses
for label, color in palette_target.items():
    subset = pca_df[pca_df['Target'] == label]
    add_covariance_ellipse(subset['PC1'], subset['PC2'], ax, color, confidence=0.95)

# Configure axis labels, title, legend, and layout formatting
